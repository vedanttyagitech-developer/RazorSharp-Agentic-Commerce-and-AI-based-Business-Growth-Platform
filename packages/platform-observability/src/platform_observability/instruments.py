"""The instruments this platform exposes, as data, each with the decision it informs.

Specification 19.13, on the voice loop but true of everything: *"Counters that are never
surfaced are not observability."* This module is the answer to that. Every instrument here
has a name, a description that becomes its ``# HELP``, its labels, and a ``decision`` --
one sentence naming what an operator does differently when the number moves. An instrument
that cannot be given that sentence does not belong in the catalogue, and
:class:`~platform_observability.metrics.InstrumentSpec` refuses to be constructed without
one.

The list is derived from what the platform actually does rather than from what is
conventional to measure: admissions and their denial codes, execution grants through their
lifecycle, the outbox and the worker that drains it, the provider, webhooks, reconciliation
and refunds. Each of those is a place where the system decides something or waits for
something, and those are the only two things worth counting.

The line this catalogue does not cross
--------------------------------------
None of these is a money record. ``commerce_refunds_open`` says how many refunds are
waiting; ``refunds`` and the hash chain in ``audit_events`` say what happened to each one.
``commerce_provider_requests_total`` says how Razorpay is behaving; ``provider_requests``
and the Money Action Proof Chain (spec 26.4) say what was sent and what came back. If a
question can only be answered from a metric, the answer is wrong -- the metric is sampled,
aggregated, capped and lost on restart, and every one of those is fine precisely because
nothing depends on it.

Adding your own
---------------
Do not edit this file to add instruments for another package. Define your own tuple of
specs beside the code that records them and register it::

    # packages/voice-runtime/src/voice_runtime/telemetry.py
    from platform_observability import InstrumentKind, InstrumentSpec

    VOICE_INSTRUMENTS = (
        InstrumentSpec(
            name="voice_frames_total",
            kind=InstrumentKind.COUNTER,
            description="Audio frames handled, by direction and disposition.",
            decision="Whether the queue is evicting under load (spec 19.13).",
            labels=("direction", "disposition"),
        ),
        ...
    )

    registry.register_all(VOICE_INSTRUMENTS)

Registration is idempotent for an identical spec and refuses a conflicting one, so two
packages can safely register the same shared catalogue and neither can silently redefine
the other's instrument.
"""

