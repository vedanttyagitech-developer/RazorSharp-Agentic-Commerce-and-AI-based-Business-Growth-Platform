def _counter(
    name: str, description: str, decision: str, labels: tuple[str, ...] = ()
) -> InstrumentSpec:
    return InstrumentSpec(
        name=name,
        kind=InstrumentKind.COUNTER,
        description=description,
        decision=decision,
        labels=labels,
    )


def _gauge(
    name: str, description: str, decision: str, labels: tuple[str, ...] = ()
) -> InstrumentSpec:
    return InstrumentSpec(
        name=name,
        kind=InstrumentKind.GAUGE,
        description=description,
        decision=decision,
        labels=labels,
    )


def _seconds(
    name: str,
    description: str,
    decision: str,
    labels: tuple[str, ...] = (),
    buckets: tuple[float, ...] = LATENCY_BUCKETS,
) -> InstrumentSpec:
    return InstrumentSpec(
        name=name,
        kind=InstrumentKind.HISTOGRAM,
        description=description,
        decision=decision,
        labels=labels,
        unit="seconds",
        buckets=buckets,
    )


