# ------------------------------------------------------------------- timings

# There is deliberately no HTTP ``Timing``. A ``timed`` block captures its metrics handle
# when it opens, and an HTTP request's tenant is not known until a dependency has resolved
# the bearer token part-way through -- so a Timing would label every request with no tenant
# and drop it. The API middleware measures with ``time.perf_counter`` and records both HTTP
# instruments after dispatch, when the tenant is known. See docs/adr/0007-observability.md.

#: One kernel admission. No outcome counter: an admission's verdict is a decision with a
#: reason code, and ``commerce_admission_denials_total`` carries it with more fidelity than
#: an ok/error label could.
ADMISSION_TIMING: Final[Timing] = Timing(duration="commerce_admission_duration_seconds")

#: One provider round trip. The outcome counter is the requests counter, so a call is
#: counted exactly once and its latency and its verdict cannot disagree. Both instruments
#: declare ``outcome``, which is what a Timing with an outcome counter requires.
PROVIDER_TIMING: Final[Timing] = Timing(
    duration="commerce_provider_request_duration_seconds",
    outcome_counter="commerce_provider_requests_total",
)

#: One leased command's handler. Duration and outcome share the ``outcome`` label, so the
#: histogram can be read for successes alone -- failures are usually fast and would
#: otherwise flatter the average.
WORKER_COMMAND_TIMING: Final[Timing] = Timing(
    duration="commerce_worker_command_duration_seconds",
    outcome_counter="commerce_worker_attempts_total",
)


# ------------------------------------------------------------ the default registry

_DEFAULT: MetricsRegistry | None = None


def default_registry() -> MetricsRegistry:
    """The process-wide registry, with :data:`PLATFORM_INSTRUMENTS` already registered.

    Three packages record into one exposition and none of them should have to be handed a
    registry object through its constructor to do it, so there is a singleton. It is
    created on first use rather than at import, because a module that builds state at
    import time is a module that cannot be tested twice in one process.

    A component that wants its own -- a test, or a second exposition on a different
    endpoint -- constructs :class:`~platform_observability.metrics.MetricsRegistry`
    directly. Nothing here requires the singleton.
    """
    global _DEFAULT
    if _DEFAULT is None:
        registry = MetricsRegistry()
        registry.register_all(PLATFORM_INSTRUMENTS)
        _DEFAULT = registry
    return _DEFAULT


def reset_default_registry() -> None:
    """Drop the process-wide registry. For tests, and for nothing else.

    Named plainly rather than hidden behind an underscore: a test that needs a clean
    registry should not have to reach into a private, and a production call site that
    reaches for this is easy to spot in review.
    """
    global _DEFAULT
    _DEFAULT = None
