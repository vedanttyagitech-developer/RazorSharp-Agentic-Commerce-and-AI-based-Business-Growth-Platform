/**
 * A readable name for a category slug, falling back to a de-slugged version of whatever
 * the server said. The server owns this vocabulary; an aisle this build has never heard
 * of must still render as itself rather than disappear.
 */
export function categoryLabel(category: string): string {
  const known = CATEGORY_LABELS[category];
  if (known) return known;
  return category
    .split(/[_-]/)
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}

/** True when the slug is one of the ten aisles this catalogue actually has. */
export function isKnownCategory(category: string): category is CategorySlug {
  return Object.prototype.hasOwnProperty.call(CATEGORY_IMAGES, category);
}

/**
 * The category a SKU belongs to, read from its middle segment.
 *
 * SKUs are `<PRODUCT>-<CATEGORY>-<NNN>`, and the segment is an abbreviation rather than
 * the slug. This is a lookup, not a guess: it is how a product page knows which aisle to
 * ask the catalogue for when all it has is a code out of the URL. An unrecognised segment
 * returns null so the caller can widen its search instead of querying a category that
 * does not exist.
 */
const SEGMENT_TO_CATEGORY: Readonly<Record<string, CategorySlug>> = {
  BAKE: "bakery",
  BEVG: "beverages",
  COND: "condiments",
  DAIRY: "dairy",
  ELEC: "electronics",
  HHLD: "household",
  PCAR: "personal_care",
  PROD: "produce",
  SNCK: "snacks",
  STPL: "staples",
};

export function categoryForSku(sku: string): CategorySlug | null {
  const segment = sku.split("-")[1];
  if (!segment) return null;
  return SEGMENT_TO_CATEGORY[segment.toUpperCase()] ?? null;
}
