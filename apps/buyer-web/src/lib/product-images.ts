/**
 * The stand-in for a SKU the merchant listed but nobody photographed.
 *
 * An inline data URI rather than a file, so it cannot itself 404 and cannot be mistaken
 * for a picture of the product. It is deliberately drawn as an empty frame: a buyer
 * should be able to tell at a glance that the shot is missing, not wonder whether the
 * thing they are buying really is a grey box.
 */
const PLACEHOLDER_SVG =
  '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 190 190">' +
  '<rect width="190" height="190" fill="#F8F8F8"/>' +
  '<rect x="47.5" y="57" width="95" height="76" rx="8" fill="none" stroke="#CCCCCC" stroke-width="3"/>' +
  '<circle cx="118" cy="80" r="7" fill="#CCCCCC"/>' +
  '<path d="M50 122l24-24 20 20 15-15 24 24" fill="none" stroke="#CCCCCC" stroke-width="3" ' +
  'stroke-linecap="round" stroke-linejoin="round"/></svg>';

export const PLACEHOLDER_IMAGE = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(PLACEHOLDER_SVG)}`;

/**
 * Every local photograph for a SKU, best shot first.
 *
 * Returns a single-element array holding the placeholder when nothing is on disk, so a
 * gallery can iterate the result without a special case and always has something to show.
 */
export function imagesFor(sku: string): string[] {
  const count = VARIANT_COUNTS[sku];
  if (!count) return [PLACEHOLDER_IMAGE];
  const paths = [`/products/${sku}.webp`];
  for (let n = 2; n <= count; n += 1) paths.push(`/products/${sku}_${n}.webp`);
  return paths;
}

/** The one shot a card or a cart line uses. */
export function primaryImage(sku: string): string {
  return VARIANT_COUNTS[sku] ? `/products/${sku}.webp` : PLACEHOLDER_IMAGE;
}

/** Whether a real photograph exists, for a caller that wants to say so out loud. */
export function hasImage(sku: string): boolean {
  return Boolean(VARIANT_COUNTS[sku]);
}

